/** [y, value] 표 (y 오름차순) */
export type Table = readonly (readonly [number, number])[];

/** 단조 3차 보간 (Fritsch–Carlson) — 측정점 사이를 출렁임 없이 매끄럽게 */
export function sample(table: Table, y: number): number {
  const n = table.length;
  if (y <= table[0][0]) return table[0][1];
  if (y >= table[n - 1][0]) return table[n - 1][1];
  let i = 0;
  while (i < n - 2 && y > table[i + 1][0]) i++;
  const [x0, y0] = table[i];
  const [x1, y1] = table[i + 1];
  const h = x1 - x0;
  const d = (y1 - y0) / h;
  const slope = (k: number): number => {
    if (k <= 0 || k >= n - 1) return d;
    const dl = (table[k][1] - table[k - 1][1]) / (table[k][0] - table[k - 1][0]);
    const dr = (table[k + 1][1] - table[k][1]) / (table[k + 1][0] - table[k][0]);
    if (dl * dr <= 0) return 0;
    return (2 * dl * dr) / (dl + dr);
  };
  const m0 = slope(i);
  const m1 = slope(i + 1);
  const t = (y - x0) / h;
  const t2 = t * t;
  const t3 = t2 * t;
  return (2 * t3 - 3 * t2 + 1) * y0 + (t3 - 2 * t2 + t) * h * m0 + (-2 * t3 + 3 * t2) * y1 + (t3 - t2) * h * m1;
}

